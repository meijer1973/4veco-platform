def check_baseline():
    base=json.loads((OUT/'baseline.json').read_text(encoding='utf-8'))
    assert native() == base['raw_native'], 'Native bytes changed; do not restore them'
    assert archives() == base['archives'], 'Archive member/CRC drift'
    assert protected() == base['protected'], 'Protected source/metadata drift'
    for name,value in base['old_proofs'].items():
        assert sha((ROOT/name).read_bytes()) == value, ('Old proof changed',name)
    supplemental=OUT/'inherited-proof-supplement.json'
    if supplemental.exists():
        for name,value in json.loads(supplemental.read_text(encoding='utf-8'))['files'].items():
            assert sha((ROOT/name).read_bytes()) == value['raw_sha256'], ('Inherited proof changed',name)
    return base


def next_revision():
    worktrees=subprocess.check_output(['git','worktree','list','--porcelain'],cwd=ROOT).decode('utf-8').splitlines()
    used=[]
    for line in worktrees:
        if not line.startswith('worktree '):
            continue
        path=Path(line[9:])/'reports'
        if path.is_dir():
            for directory, children, files in os.walk(path):
                for name in children:
                    match=PROOF_COMPONENT.fullmatch(name)
                    if match:
                        used.append(dict(path=str(Path(directory)/name), revision=int(match[1]), kind='proof_directory'))
                for name in files:
                    candidate=Path(directory)/name
                    if '212' in str(candidate) and re.search(r'(attempt|reserv)',name,re.I):
                        matches=re.findall(r'(?:^|[-_])r([1-9][0-9]*)(?=[-_.]|$)',name)
                        if not matches and candidate.suffix=='.json':
                            matches=re.findall(r'"(?:revision|proof_suffix|suffix)"\s*:\s*"r([1-9][0-9]*)"',candidate.read_text(encoding='utf-8'))
                        for number in matches:
                            used.append(dict(path=str(candidate), revision=int(number), kind='reservation_or_attempt'))
    local_attempts=list(OUT.glob('attempt-r*.json'))
    numbers=[int(re.search(r'r(\d+)',p.name)[1]) for p in local_attempts]+[row['revision'] for row in used]
    number=max(numbers, default=0)+1
    revision=f'r{number}'
    save('attempt-'+revision+'.json',dict(state='ATTEMPT_RECORDED', revision=revision,
        existing_registered_worktree_proofs=used, python=PYTHON, path=os.environ.get('PATH','')))
    return revision


def compare_pages(manifest):
    from PIL import Image, ImageChops
    comparisons=[]
    for kind,doc,count in zip(KINDS,manifest['documents'],(14,7,6)):
        new_dir=Path(doc['proof_directory'])
        old_dir=R9/f"212-{kind}-{doc['pdf_sha256'][:12]}-r9"
        previous=json.loads((old_dir/'manifest.json').read_text(encoding='utf-8'))
        current=json.loads((new_dir/'manifest.json').read_text(encoding='utf-8'))
        assert previous['inspection_status'] == current['inspection_status'] == 'PENDING'
        before=sorted((old_dir/'pages').glob('page-*.png'))
        after=sorted((new_dir/'pages').glob('page-*.png'))
        assert len(before)==len(after)==count
        for old,new in zip(before,after):
            assert old.read_bytes()==new.read_bytes(), (kind,new.name,'PNG bytes differ')
            with Image.open(old) as a,Image.open(new) as z:
                assert a.size == z.size
                assert ImageChops.difference(a.convert('RGB'),z.convert('RGB')).getbbox() is None
            comparisons.append(dict(kind=kind,old=old.relative_to(ROOT).as_posix(),
                current=new.relative_to(ROOT).as_posix(),sha256=sha(new.read_bytes()),pixel_delta=None))
    assert len(comparisons)==27
    return comparisons


