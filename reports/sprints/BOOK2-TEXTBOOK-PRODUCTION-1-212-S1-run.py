def supplement():
    """Bind every inherited proof path to immutable Git; do not replace baseline."""
    listing = subprocess.check_output(['git','ls-tree','-rz','--full-tree',PBASE,'reports'],cwd=ROOT)
    result = {}
    for entry in listing.split(b'\0'):
        if not entry:
            continue
        meta, encoded = entry.split(b'\t',1)
        name = encoded.decode('utf-8')
        if not any(PROOF_COMPONENT.fullmatch(part) for part in Path(name).parts):
            continue
        blob = subprocess.check_output(['git','cat-file','blob',meta.split()[2].decode()],cwd=ROOT)
        raw = (ROOT/name).read_bytes()
        comparable = raw.replace(b'\r\n',b'\n') if Path(name).suffix in ('.json','.md','.txt') else raw
        assert comparable == blob, ('Inherited proof differs from PBASE',name)
        result[name] = dict(raw_sha256=sha(raw), git_blob_sha256=sha(blob))
    assert result and any('-r9/' in name for name in result)
    save('inherited-proof-supplement.json',dict(platform_base=PBASE, files=result,
         reason='Initial snapshot covered standard root only; this supplement binds all inherited nested proofs directly to immutable PBASE, after diagnostic r7 and before valid succession reproduction.'))
    print(f'Immutable PBASE supplemental proof binding: {len(result)} files.')


