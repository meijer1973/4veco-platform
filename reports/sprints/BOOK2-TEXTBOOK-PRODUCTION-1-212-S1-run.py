def sha(value):
    return hashlib.sha256(value).hexdigest()


def save(name, value):
    OUT.mkdir(exist_ok=True)
    with (OUT / name).open('x', encoding='utf-8', newline='\n') as stream:
        stream.write(json.dumps(value, ensure_ascii=False, indent=2) + '\n')


def command(argv, name, cwd=ROOT):
    start = datetime.datetime.now(datetime.timezone.utc).isoformat()
    run = subprocess.run(list(map(str,argv)), cwd=cwd, capture_output=True)
    result = dict(argv=list(map(str,argv)), cwd=str(cwd), started_at=start,
                  finished_at=datetime.datetime.now(datetime.timezone.utc).isoformat(),
                  exit_code=run.returncode, stdout=run.stdout.decode('utf-8',errors='replace'),
                  stderr=run.stderr.decode('utf-8',errors='replace'),
                  stdout_sha256=sha(run.stdout), stderr_sha256=sha(run.stderr))
    save(name, result)
    print(name, 'exit', run.returncode, flush=True)
    if run.returncode:
        raise RuntimeError(f'{name}: native exit {run.returncode}; complete output preserved')
    return result


def native():
    assert len(NATIVE) == len(set(NATIVE)) == 34
    return {name: sha((FOLDER/name).read_bytes()) for name in NATIVE}


def archives():
    result = {}
    for kind, count in zip(KINDS,(19,11,9)):
        with ZipFile(FOLDER / f'{STEM} – {kind}.zip') as archive:
            assert len(archive.namelist()) == len(set(archive.namelist())) == count
            assert archive.testzip() is None
            members = []
            for item in archive.infolist():
                data = archive.read(item.filename)
                assert data == (FOLDER/item.filename).read_bytes()
                members.append(dict(name=item.filename, crc=item.CRC, size=item.file_size,
                                    sha256=sha(data), date_time=list(item.date_time)))
            result[kind] = members
    return result


